/**
 * `@warda_protocol/core`, bundled for a browser.
 *
 * ## Why a bundle and not a rewrite
 *
 * The sandbox at /sandbox answers "what would this grant refuse?" while
 * somebody types. That answer has to come from the same function the payer runs
 * before it builds a transaction — `validateSpend` — because a second copy of
 * the rules on a marketing page is a second copy of the rules, and the first
 * time one of them changes the page starts teaching something the covenant does
 * not do.
 *
 * The agent pages already avoid that by computing refusals in `dashboard.ts`
 * and publishing them. A sandbox cannot: the terms change as you type, so the
 * rules have to be in the browser.
 *
 * ## Why it is generated and committed
 *
 * `site/build.py` is Python and does not shell out to node, and a site build
 * on a machine with no node must still produce a site. So this runs in the npm
 * workspace, writes into `site/src/`, and the file is committed like any other
 * asset the page needs.
 *
 * `ops/check-core-browser.mjs` refuses a bundle older than the source it came
 * from — the same job `check-dist` does for the packages, for the same reason:
 * a stale bundle is green and wrong at the same time, and this one is wrong in
 * public.
 */
import { build } from "esbuild";
import { writeFileSync, readFileSync } from "node:fs";
import { resolve, dirname } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
export const OUT = resolve(root, "site/src/core-browser.js");

export const BANNER =
  "/* GENERATED by ops/build-core-browser.mjs from @warda_protocol/core.\n" +
  "   Do not edit: it is overwritten, and editing it would create the second\n" +
  "   copy of the rules this file exists to prevent.\n" +
  "   Rebuild:  node ops/build-core-browser.mjs  */\n";

/**
 * The bundle, as text, without writing it.
 *
 * Exported so `ops/check-core-browser.mjs` can ask "is the committed file what
 * this would produce?" rather than comparing timestamps. It has to: this file
 * is COMMITTED, and git does not preserve mtimes — on a fresh checkout every
 * file is stamped at clone time in whatever order the objects were written, so
 * a timestamp comparison in CI is a coin toss dressed as a check. Comparing
 * the bytes is the same question with a real answer.
 */
export async function bundleText() {
  const result = await build({
    entryPoints: [resolve(root, "ops/core-browser-entry.js")],
    bundle: true,
    format: "iife",
    globalName: "WardaCore",
    platform: "browser",
    target: "es2022",
    write: false,
    legalComments: "none",
  });
  return BANNER + result.outputFiles[0].text;
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? "").href) {
  writeFileSync(OUT, await bundleText());
  console.log(`site/src/core-browser.js: ${(readFileSync(OUT).length / 1024).toFixed(1)} KB`);
}
