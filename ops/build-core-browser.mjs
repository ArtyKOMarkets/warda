/**
 * `@warda_protocol/core`, bundled for a browser.
 *
 * ## Why a bundle and not a rewrite
 *
 * The sandbox at /sandbox answers "what would this grant refuse?" while
 * somebody types. That answer has to come from the same function the payer runs
 * before it builds a transaction — `validateSpend` — because a second copy of
 * the rules on a marketing page is a second copy of the rules, and the first
 * time one of them changes the page starts teaching something the covenant does
 * not do.
 *
 * The agent pages already avoid that by computing refusals in `dashboard.ts`
 * and publishing them. A sandbox cannot: the terms change as you type, so the
 * rules have to be in the browser.
 *
 * ## Why it is generated and committed
 *
 * `site/build.py` is Python and does not shell out to node, and a site build
 * on a machine with no node must still produce a site. So this runs in the npm
 * workspace, writes into `site/src/`, and the file is committed like any other
 * asset the page needs.
 *
 * `ops/check-core-browser.mjs` refuses a bundle older than the source it came
 * from — the same job `check-dist` does for the packages, for the same reason:
 * a stale bundle is green and wrong at the same time, and this one is wrong in
 * public.
 */
/**
 * esbuild is NOT a root dependency. It is declared by the `cli` workspace and
 * hoisted, which is why an import from `ops/` resolves at all — `npm ci` at the
 * root installs workspace devDependencies, so CI has it too.
 *
 * That is a reliance nothing declares, and the failure it sets up is the bad
 * kind: if `cli` ever drops esbuild, the guard that exists to catch a stale
 * bundle becomes the thing that breaks, and the message would be a module
 * resolution error with no hint that the sandbox is what stopped working. So
 * it says so instead.
 *
 * To make it a fact rather than a comment:  npm i -D esbuild  (at the root).
 */
let build;
try {
  ({ build } = await import("esbuild"));
} catch (e) {
  console.error(
    "esbuild is not installed.\n\n" +
      "It reaches this script by being hoisted out of the `cli` workspace rather\n" +
      "than by being declared at the root, so an unrelated change in `cli` can take\n" +
      "it away. site/src/core-browser.js is what /sandbox runs to say what a grant\n" +
      "would refuse, and it cannot be built without this.\n\n" +
      "  npm i -D esbuild",
  );
  process.exit(1);
}
import { writeFileSync, readFileSync } from "node:fs";
import { resolve, dirname } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");

/**
 * Every browser bundle this repository ships, built by this one file.
 *
 * There was one. The console's funding planner needed a second — the router's
 * own `planFunding`, rather than a description of the rail written for a page —
 * and the obvious move was `build-router-browser.mjs` beside this one, with a
 * `check-router-browser.mjs` beside its check. That would have been two copies
 * of the builder, which is extracted-then-copied a thirteenth time, in the file
 * whose whole job is preventing it.
 *
 * `alias` is how a bundle takes only what the page runs. The router imports
 * `decodeAddress` from `@warda_protocol/kaspa`, whose index also exports the
 * signer — and the signer imports `node:child_process`, which no browser has.
 * So the planner's bundle resolves that package to `sdk/src/address.ts`, the
 * real implementation, whose only import is `./bytes.ts`. Not a stub: the same
 * source the package ships. If the router ever imports anything else from
 * kaspa, this build fails with a missing export, which is the loud way.
 */
export const BUNDLES = {
  core: {
    entry: "ops/core-browser-entry.js",
    out: "site/src/core-browser.js",
    global: "WardaCore",
    from: "@warda_protocol/core",
    alias: {},
  },
  router: {
    entry: "ops/router-browser-entry.js",
    out: "site/src/router-browser.js",
    global: "WardaRouter",
    from: "@warda_protocol/router",
    alias: {
      "@warda_protocol/kaspa": "./sdk/src/address.ts",
      "@warda_protocol/core": "./src/index.ts",
    },
  },
};

/* Kept for anything that imported the single-bundle names. */
export const OUT = resolve(root, BUNDLES.core.out);

const bannerFor = (name) =>
  `/* GENERATED by ops/build-core-browser.mjs from ${BUNDLES[name].from}.\n` +
  "   Do not edit: it is overwritten, and editing it would create the second\n" +
  "   copy of the rules this file exists to prevent.\n" +
  "   Rebuild:  node ops/build-core-browser.mjs  */\n";
export const BANNER = bannerFor("core");

/**
 * The bundle, as text, without writing it.
 *
 * Exported so `ops/check-core-browser.mjs` can ask "is the committed file what
 * this would produce?" rather than comparing timestamps. It has to: this file
 * is COMMITTED, and git does not preserve mtimes — on a fresh checkout every
 * file is stamped at clone time in whatever order the objects were written, so
 * a timestamp comparison in CI is a coin toss dressed as a check. Comparing
 * the bytes is the same question with a real answer.
 */
export async function bundleText(name = "core") {
  const b = BUNDLES[name];
  const result = await build({
    entryPoints: [resolve(root, b.entry)],
    alias: b.alias,
    /* PIN THE WORKING DIRECTORY. esbuild writes a `// path/to/file` comment
       above each module, relative to `process.cwd()` — so the same sources
       produce different BYTES depending on where node was started. CI runs the
       check from the repo root and site/refresh-demo.sh runs it from `site/`,
       which turned all eleven of those comments into `../src/...` and made the
       byte comparison fail by exactly 33 characters on the deploy path while
       passing in CI.

       A guard that depends on the caller's cwd is a guard that fires where it
       is run rather than where something is wrong. This makes the output a
       function of the sources alone. */
    absWorkingDir: root,
    bundle: true,
    format: "iife",
    globalName: b.global,
    platform: "browser",
    target: "es2022",
    write: false,
    legalComments: "none",
  });
  return bannerFor(name) + result.outputFiles[0].text;
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? "").href) {
  for (const name of Object.keys(BUNDLES)) {
    const out = resolve(root, BUNDLES[name].out);
    writeFileSync(out, await bundleText(name));
    console.log(`${BUNDLES[name].out}: ${(readFileSync(out).length / 1024).toFixed(1)} KB`);
  }
}
