/**
 * registry/deploy/sources.json, generated from site/src/services.json.
 *
 * The hosted endpoint cannot read a file outside its own directory — a runtime
 * resolution is invisible to the bundler that traces the function's imports, so
 * the file is simply not uploaded and the failure appears as a path under
 * /var/task that no local checkout has. The MCP endpoint's covenant template is
 * copied there for exactly this reason.
 *
 * So there has to be a copy, and the moment a copy exists it must be generated.
 * Extracted-then-copied is the failure this repo has now paid for six times:
 * members.ts, the shared agent CSS, four files each claiming a different MCP
 * version, three copies of the fee parser, twelve tools demanding --rpc, and
 * the site's recorded commands.
 *
 *     node ops/build-registry-sources.mjs            write it
 *     node ops/build-registry-sources.mjs --check    fail if it is behind
 */
import { readFileSync, writeFileSync } from "node:fs";
import { resolve, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const from = resolve(root, "site/src/services.json");
const to = resolve(root, "registry/deploy/api/sources.ts");

const registry = JSON.parse(readFileSync(from, "utf8"));
const sources = registry.sources ?? [];

const bad = sources.filter((u) => {
  try {
    return new URL(u).protocol !== "https:";
  } catch {
    return true;
  }
});
if (bad.length > 0) {
  console.error("a source must be an https URL:\n" + bad.map((b) => `  ${b}`).join("\n"));
  process.exit(1);
}

/**
 * The registry's URL exists in two places that cannot import each other:
 * `DEFAULT_REGISTRY` in the PUBLISHED mcp package, which is where every agent
 * that installs it will look, and `registry` in services.json, which is where
 * /network looks. A published default cannot be corrected by editing a file —
 * agents keep the version they installed — so these disagreeing is not a
 * cosmetic bug: it is half the callers pointed at a host that may not exist.
 *
 * Checked rather than generated, because one of the two is inside a release.
 * An empty `registry` means the site has not been pointed at one yet and is
 * rendering the file, which is a real state and not a mismatch.
 */
const siteRegistry = (registry.registry ?? "").replace(/\/+$/, "");
if (siteRegistry !== "") {
  const discover = readFileSync(resolve(root, "mcp/src/discover.ts"), "utf8");
  const m = discover.match(/DEFAULT_REGISTRY\s*=\s*"([^"]+)"/);
  const packaged = (m?.[1] ?? "").replace(/\/+$/, "");
  if (packaged !== siteRegistry) {
    console.error(
      "the registry URL disagrees between the site and the published MCP tool:\n\n" +
        `  site/src/services.json  ${siteRegistry || "(empty)"}\n` +
        `  mcp/src/discover.ts     ${packaged || "(none found)"}\n\n` +
        "Agents keep the version of the tool they installed, so the packaged default cannot be\n" +
        "fixed by editing a file. If it has to change, it changes in a release.",
    );
    process.exit(1);
  }
}

/* A TypeScript module, not JSON, and that is the point. A JSON file read at
   runtime is invisible to the bundler tracing the function's imports, so
   whether it reaches the deployment depends on the bundler noticing a pattern
   it is not obliged to notice. A module the function imports is a module the
   bundler must include. */
const out =
  `/* GENERATED by ops/build-registry-sources.mjs from site/src/services.json.\n` +
  `   Do not edit.\n\n` +
  `   These are POINTERS, not claims. The registry fetches each one from the\n` +
  `   operator's own domain and checks its signature on every request, so an\n` +
  `   entry here cannot make a bad listing appear — it can only point at\n` +
  `   something that fails verification and shows up in \`dropped\`.\n\n` +
  `   Being in this list is not a condition of being usable: an agent that\n` +
  `   knows an endpoint reads its /.well-known/warda-service.json directly,\n` +
  `   with no registry involved. */\n` +
  `export const sources: string[] = ${JSON.stringify(sources, null, 2)};\n`;

if (process.argv.includes("--check")) {
  const have = readFileSync(to, "utf8");
  if (have !== out) {
    console.error(
      "registry/deploy/api/sources.ts is behind site/src/services.json.\n\n" +
        "The hosted endpoint serves the file in its own directory, so a stale copy is an index\n" +
        "that silently does not contain a service somebody was told they had listed.\n\n" +
        "  node ops/build-registry-sources.mjs",
    );
    process.exit(1);
  }
  console.log(`registry sources: ${sources.length} pointer(s), and the deploy copy is current.`);
  process.exit(0);
}

writeFileSync(to, out);
console.log(`registry/deploy/api/sources.ts: ${sources.length} pointer(s)`);
