/**
 * registry/deploy/sources.json, generated from site/src/services.json.
 *
 * The hosted endpoint cannot read a file outside its own directory — a runtime
 * resolution is invisible to the bundler that traces the function's imports, so
 * the file is simply not uploaded and the failure appears as a path under
 * /var/task that no local checkout has. The MCP endpoint's covenant template is
 * copied there for exactly this reason.
 *
 * So there has to be a copy, and the moment a copy exists it must be generated.
 * Extracted-then-copied is the failure this repo has now paid for six times:
 * members.ts, the shared agent CSS, four files each claiming a different MCP
 * version, three copies of the fee parser, twelve tools demanding --rpc, and
 * the site's recorded commands.
 *
 *     node ops/build-registry-sources.mjs            write it
 *     node ops/build-registry-sources.mjs --check    fail if it is behind
 */
import { readFileSync, writeFileSync } from "node:fs";
import { resolve, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const from = resolve(root, "site/src/services.json");
const to = resolve(root, "registry/deploy/sources.json");

const registry = JSON.parse(readFileSync(from, "utf8"));
const sources = registry.sources ?? [];

const bad = sources.filter((u) => {
  try {
    return new URL(u).protocol !== "https:";
  } catch {
    return true;
  }
});
if (bad.length > 0) {
  console.error("a source must be an https URL:\n" + bad.map((b) => `  ${b}`).join("\n"));
  process.exit(1);
}

const out =
  JSON.stringify(
    {
      _comment:
        "GENERATED by ops/build-registry-sources.mjs from site/src/services.json. Do not edit. " +
        "These are POINTERS, not claims — the registry fetches each one from the operator's own " +
        "domain and checks its signature on every request, so an entry here cannot make a bad " +
        "listing appear. It can only point at something that fails verification and shows up in " +
        "`dropped`. Being in this list is not a condition of being usable: an agent that knows an " +
        "endpoint reads its /.well-known/warda-service.json directly, with no registry involved.",
      sources,
    },
    null,
    2,
  ) + "\n";

if (process.argv.includes("--check")) {
  const have = readFileSync(to, "utf8");
  if (have !== out) {
    console.error(
      "registry/deploy/sources.json is behind site/src/services.json.\n\n" +
        "The hosted endpoint serves the file in its own directory, so a stale copy is an index\n" +
        "that silently does not contain a service somebody was told they had listed.\n\n" +
        "  node ops/build-registry-sources.mjs",
    );
    process.exit(1);
  }
  console.log(`registry sources: ${sources.length} pointer(s), and the deploy copy is current.`);
  process.exit(0);
}

writeFileSync(to, out);
console.log(`registry/deploy/sources.json: ${sources.length} pointer(s)`);
